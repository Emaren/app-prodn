def write_once(path,x):
    need(path.parent==STATE and not path.is_symlink(),"linked record")
    b=canonical(x);need(len(b)<=262144,"record size")
    fd=os.open(path,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600)
    with os.fdopen(fd,"wb")as f:
        f.write(b);f.flush();os.fsync(f.fileno())
    d=os.open(STATE,os.O_RDONLY|os.O_DIRECTORY)
    try:os.fsync(d)
    finally:os.close(d)
    return digest(b)
