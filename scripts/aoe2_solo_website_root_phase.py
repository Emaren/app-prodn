def verify_signature(x):
    need(type(x) is dict and set(x)=={"schema","policy","payload","signature_base64"}
         and x.get("schema")==1 and x.get("policy")==POLICY and
         type(x.get("payload")) is dict,"bad signed envelope")
    p=x["payload"]
    need(type(x["signature_base64"])is str,"missing signature")
    try:sig=base64.b64decode(x["signature_base64"],validate=True)
    except (ValueError,TypeError)as exc:raise Hold("invalid signature encoding")from exc
    need(64<=len(sig)<=8192,"signature length")
    trusted_key()
    with tempfile.TemporaryDirectory(prefix="solo-v1-owner-verify-")as t:
        data,path=pathlib.Path(t)/"data",pathlib.Path(t)/"signature"
        data.write_bytes(DOMAIN+canonical(p));path.write_bytes(sig)
        r=subprocess.run(["/usr/bin/openssl","dgst","-sha256","-verify",str(KEY),
                          "-signature",str(path),str(data)],
                         capture_output=True,timeout=10)
    need(r.returncode==0,"owner signature invalid")
    return p
