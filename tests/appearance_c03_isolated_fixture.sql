-- ONLY for a fresh temporary UID650 PostgreSQL cluster. NEVER PRODUCTION.
-- Execute as a fresh 'postgres' superuser on a localhost-bound isolated
-- test instance whose data dir is private to UID650.
CREATE ROLE aoe2hd_user LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE aoe2war_web_prod LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE aoe2war_r25_web_ro LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE DATABASE aoe2hd_db OWNER aoe2hd_user;
-- PG14 default public schema permits CREATE to PUBLIC; real HEL1 catalog
-- explicitly denies web CREATE. Reproduce that physical preimage here.
\connect aoe2hd_db
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
\connect postgres
\connect aoe2hd_db
SET ROLE aoe2hd_user;
CREATE TABLE public.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid varchar(100) UNIQUE NOT NULL,
  is_admin boolean NOT NULL DEFAULT false,
  in_game_name text,
  steam_persona_name varchar(255),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.site_theme_campaign (
  slot smallint PRIMARY KEY DEFAULT 1 CHECK (slot=1),
  campaign_key varchar(64) NOT NULL UNIQUE,
  label varchar(120) NOT NULL,
  enabled boolean NOT NULL DEFAULT false,
  theme_key varchar(20) NOT NULL
    CHECK (theme_key IN ('black','grey','white','sepia','walnut','crimson','midnight')),
  starts_at timestamp NOT NULL,
  ends_at timestamp NOT NULL,
  updated_by_user_id integer REFERENCES public.users(id),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT site_theme_campaign_window_check CHECK (starts_at<ends_at)
);
CREATE TABLE public.user_theme_campaign_overrides (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_key varchar(64) NOT NULL,
  user_id integer NOT NULL REFERENCES public.users(id),
  theme_key varchar(20) NOT NULL
    CHECK (theme_key IN ('black','grey','white','sepia','walnut','crimson','midnight')),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_user_theme_campaign_override UNIQUE(campaign_key,user_id)
);
CREATE TABLE public.user_appearance_preferences (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES public.users(id),
  theme_key varchar(20) NOT NULL
);
CREATE TABLE public.user_activity_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public.users(id),
  type varchar(40) NOT NULL,
  path varchar(160),
  label varchar(80),
  metadata jsonb,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.bet_wagers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES public.users(id),
  amount integer NOT NULL
);
